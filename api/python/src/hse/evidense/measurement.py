    @staticmethod    
    def calculate_absorbance(baseline, measurement, correctionFactor = Quadruple(1.0)):
        ods = Quadruple()
        if(baseline.channel230.reference == 0 or measurement.channel230.sample == 0):
            ods.value230 = float('NaN')
        else:
            ods.value230 = math.log(baseline.channel230.sample / baseline.channel230.reference * measurement.channel230.reference / measurement.channel230.sample * correctionFactor.value230, 10)

        if(baseline.channel260.reference == 0 or measurement.channel260.sample == 0):
            ods.value260 = float('NaN')
        else:
            ods.value260 = math.log(baseline.channel260.sample / baseline.channel260.reference * measurement.channel260.reference / measurement.channel260.sample * correctionFactor.value260, 10)

        if(baseline.channel280.reference == 0 or measurement.channel280.sample == 0):
            ods.value280 = float('NaN')
        else:
            ods.value280 = math.log(baseline.channel280.sample / baseline.channel280.reference * measurement.channel280.reference / measurement.channel280.sample * correctionFactor.value280, 10)

        if(baseline.channel340.reference == 0 or measurement.channel340.sample == 0):
            ods.value340 = float('NaN')
        else:
            ods.value340 = math.log(baseline.channel340.sample / baseline.channel340.reference * measurement.channel340.reference / measurement.channel340.sample * correctionFactor.value340, 10)
        return ods

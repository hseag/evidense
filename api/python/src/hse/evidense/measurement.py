class Results:
    """Calculated concentration, purity, and absorbance results."""

    def __init__(self, ds_dna, ss_dna, ss_rna, purity_ratio_260_230, purity_ratio_260_280, a230 = None, a260 = None, a280 = None, a340 = None):
        """Initialize a result set for one measurement."""
        self.ds_dna              = ds_dna
        self.ss_dna              = ss_dna
        self.ss_rna              = ss_rna
        self.purity_ratio_260_230 = purity_ratio_260_230
        self.purity_ratio_260_280 = purity_ratio_260_280
        self.a230                = a230
        self.a260                = a260
        self.a280                = a280
        self.a340                = a340
        
    def __repr__(self):
        ret = "ds_dna:{} ss_dna:{} ss_rna:{} 260/230:{} 260/280:{}".format(self.ds_dna, self.ss_dna, self.ss_rna, self.purity_ratio_260_230, self.purity_ratio_260_280)
        if self.a230 is not None:
            ret += " a230:{} a260:{} a280:{} a340:{}".format(self.a230, self.a260, self.a280, self.a340)
        return ret
        
    def to_json(self):
        """Convert the results to a JSON-compatible dictionary."""
        m = { DictKeys.DSDNA         : self.ds_dna,
              DictKeys.SSDNA         : self.ss_dna,
              DictKeys.SSRNA         : self.ss_rna,
              DictKeys.PURITY260_230 : self.purity_ratio_260_230,
              DictKeys.PURITY260_280 : self.purity_ratio_260_280,
            }
        if self.a230 is not None:
            m[DictKeys.A230] = self.a230
            m[DictKeys.A260] = self.a260
            m[DictKeys.A280] = self.a280
            m[DictKeys.A340] = self.a340
        return m;
        
    def __eq__(self, rhs):
        delta = 0.00000001
        
        def compare_optional(lhs, rhs):
            if lhs is None or rhs is None:
                return True
            return math.isclose(lhs, rhs, rel_tol = delta)

        return math.isclose(self.ds_dna, rhs.ds_dna, rel_tol = delta) and math.isclose(self.ss_dna, rhs.ss_dna, rel_tol = delta) and math.isclose(self.ss_rna, rhs.ss_rna, rel_tol = delta) and math.isclose(self.purity_ratio_260_230, rhs.purity_ratio_260_230, rel_tol = delta) and math.isclose(self.purity_ratio_260_280, rhs.purity_ratio_260_280, rel_tol = delta) and compare_optional(self.a230, rhs.a230) and compare_optional(self.a260, rhs.a260) and compare_optional(self.a280, rhs.a280) and compare_optional(self.a340, rhs.a340)

    @staticmethod
    def from_json(node):
        """Create a result set from a JSON dictionary."""
        return Results(node[DictKeys.DSDNA], node[DictKeys.SSDNA], node[DictKeys.SSRNA], node[DictKeys.PURITY260_230], node[DictKeys.PURITY260_280], node.get(DictKeys.A230), node.get(DictKeys.A260), node.get(DictKeys.A280), node.get(DictKeys.A340))
        
class Factors:
    """Correction factors derived from blank measurements."""

    def __init__(self, factor_a_buffer_blank = None):
        """Initialize correction factors."""
        self.f_a_buffer_blank  = factor_a_buffer_blank or Quadruple(0.0)

    def __repr__(self):
        return "f_a_buffer_blank:{}".format(self.f_a_buffer_blank)
        
    def __add__(self, rhs):
        ret = Factors()

        ret.f_a_buffer_blank  = self.f_a_buffer_blank  + rhs.f_a_buffer_blank

        return ret

    def __truediv__(self, rhs):
        ret = Factors()

        if isinstance(rhs, Factors):
            ret.f_a_buffer_blank  = self.f_a_buffer_blank  / rhs.f_a_buffer_blank
        else:
            ret.f_a_buffer_blank  = self.f_a_buffer_blank  / rhs

        return ret

    def to_json(self):
            """Convert the factors to a JSON-compatible dictionary."""
            return  { DictKeys.BUFFER_BLANK : self.f_a_buffer_blank.to_json()}

    @staticmethod
    def from_json(node):
        """Create correction factors from a JSON dictionary."""
        return Factors( Quadruple.from_json(node[DictKeys.BUFFER_BLANK]))

class Measurement:
    """Represents one baseline-air-sample measurement triplet."""

    def __init__(self, baseline, air, sample, comment = None):
        """Initialize a measurement from baseline, air, and sample steps."""
        self._comment           = comment
        self._baseline          = baseline
        self._air               = air
        self._sample            = sample

    def __repr__(self):
        return "baseline:{} air:{} sample:{}".format(self._baseline, self._air, self._sample)

    def absorbance(self, factor_a_buffer_blank = Quadruple(0.0), device_settings = None):
        """Calculate absorbance values for the measurement."""
        aNNN = self.calculate_absorbance(self._air, self._sample) - factor_a_buffer_blank
        if not device_settings is None:
            a280_real        = self._get_theoretical_dna_absorption(device_settings.center_wavelength_280)
            a280_theoretical = self._get_theoretical_dna_absorption(280.0)

            a280_orig     = aNNN.value280
            aNNN.value280 = aNNN.value280 * a280_theoretical / a280_real
        return aNNN
                                                                    
    def set_comment(self, comment):
        """Set or replace the measurement comment."""
        self._comment = comment

    def comment(self):
        """Return the measurement comment."""
        return self._comment

    def factor_a_buffer_blank(self):
        """Return the blank absorbance factor derived from air and sample."""
        return self.calculate_absorbance(self._air, self._sample)
        
    def factors(self):
        """Return the correction factors represented by this measurement."""
        return Factors(self.factor_a_buffer_blank())

